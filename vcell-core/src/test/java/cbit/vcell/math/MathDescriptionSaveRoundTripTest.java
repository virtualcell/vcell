package cbit.vcell.math;

import cbit.vcell.biomodel.BioModel;
import cbit.vcell.mapping.SimulationContext;
import cbit.vcell.resource.PropertyLoader;
import cbit.vcell.xml.XMLSource;
import cbit.vcell.xml.XmlHelper;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import org.vcell.sbml.VcmlTestSuiteFiles;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.List;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

/**
 * A generated math description must compare equal to itself after a save.
 * <p>
 * {@code ServerDocumentManager} decides whether to re-save a MathDescription by comparing the
 * math held in the database against the freshly generated math with {@code compareEqual}. A new
 * MathDescription key forces every Simulation in the application to be re-saved under a new key,
 * and a simulation only keeps its results if it also earns a parent reference. So if generated
 * math is never equal to its own saved form, every save silently re-keys every simulation - and a
 * run that is still in flight at that moment is stranded, reporting "never ran".
 * <p>
 * That is not hypothetical. Two fields used to be generated but not persisted, so the difference
 * was invisible in the saved file and visible only to comparison:
 * <ul>
 *   <li>{@code Action.operand} - set to 1.0 for create/destroy actions, which
 *       {@code Action.getVCML()} writes only for {@code inc}, so readers rebuilt them with null.</li>
 *   <li>{@code LangevinParticleJumpProcess.bondLength} - set for every subtype, though only
 *       BINDING persists one.</li>
 * </ul>
 * Both made every SpringSaLaD and rule-based application fail this test.
 * <p>
 * This is deliberately the identical tier ({@code compareEqual}), not the equivalence tier.
 * {@code MathGenCompareTest} asserts only equivalency, which is what decides whether results carry
 * over - it cannot see the re-keying, because re-keying is governed by exact equality.
 */
@Tag("Fast")
public class MathDescriptionSaveRoundTripTest {

    /**
     * Applications whose math is generated by the particle math mappings. Restricted to these
     * because they are what the two defects affected and they generate quickly; the invariant
     * itself is not particle-specific.
     */
    private static final List<String> PARTICLE_MODELS = Arrays.asList(
            // SpringSaLaD (LangevinMathMapping)
            "biomodel_267795255.vcml",
            "biomodel_269452600.vcml",
            "biomodel_302567430.vcml",
            "biomodel_313167724.vcml",
            "biomodel_315318780.vcml",
            "biomodel_316363705.vcml",
            "biomodel_316365832.vcml",
            // rule-based / NFSim (RulebasedMathMapping)
            "biomodel_97705317.vcml",
            "biomodel_97075423.vcml"
    );

    public static Collection<String> testCases() throws Exception {
        PropertyLoader.setProperty(PropertyLoader.installationRoot, "..");
        List<String> cases = new ArrayList<>();
        for (String filename : PARTICLE_MODELS) {
            BioModel biomodel = XmlHelper.XMLToBioModel(new XMLSource(readVcml(filename)));
            for (SimulationContext simContext : biomodel.getSimulationContexts()) {
                if (isParticleApplication(simContext)) {
                    cases.add(filename + ":" + simContext.getName());
                }
            }
        }
        return cases;
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("testCases")
    public void generated_math_equals_its_own_saved_form(String filename_colon_appname) throws Exception {
        PropertyLoader.setProperty(PropertyLoader.installationRoot, "..");
        String filename = filename_colon_appname.substring(0, filename_colon_appname.indexOf(':'));
        String simContextName = filename_colon_appname.substring(filename.length() + 1);

        BioModel biomodel = XmlHelper.XMLToBioModel(new XMLSource(readVcml(filename)));
        biomodel.refreshDependencies();
        SimulationContext simContext = biomodel.getSimulationContext(simContextName);
        simContext.updateAll(false);
        MathDescription generated = simContext.getMathDescription();

        // exactly what the database round trip does: written as VCML, read back, compared on the next save
        MathDescription reloaded = MathDescription.fromEditor(generated, generated.getVCML_database());

        if (!generated.compareEqual(reloaded)) {
            fail("generated math for '" + filename_colon_appname + "' does not compare equal to itself "
                    + "after a save/reload round trip, so every save will re-key every simulation in this "
                    + "application and strand any run still in flight. Look for state that is generated but "
                    + "not written by MathDescription.getVCML_database(). Differences: "
                    + MathDescriptionDifferences.describe(generated, reloaded));
        }
        // the reverse direction too - Compare.isEqual(List,List) only ever evaluates v1[i].compareEqual(v2[i]),
        // so an asymmetric compareEqual passes in one direction and fails in the other.
        assertTrue(reloaded.compareEqual(generated),
                "math comparison is asymmetric for '" + filename_colon_appname + "'");
    }

    private static boolean isParticleApplication(SimulationContext simContext) {
        SimulationContext.Application type = simContext.getApplicationType();
        return type == SimulationContext.Application.SPRINGSALAD
                || type == SimulationContext.Application.RULE_BASED_STOCHASTIC;
    }

    private static String readVcml(String filename) throws Exception {
        try (InputStream is = VcmlTestSuiteFiles.getVcmlTestCase(filename)) {
            return new BufferedReader(new InputStreamReader(is)).lines().collect(Collectors.joining("\n"));
        }
    }
}
