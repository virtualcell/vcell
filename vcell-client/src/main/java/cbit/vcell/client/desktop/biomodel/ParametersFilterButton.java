package cbit.vcell.client.desktop.biomodel;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;

import javax.swing.ButtonGroup;
import javax.swing.JButton;
import javax.swing.JCheckBoxMenuItem;
import javax.swing.JMenuItem;
import javax.swing.JPopupMenu;
import javax.swing.JRadioButtonMenuItem;

import cbit.vcell.mapping.SimulationContext;

/**
 * The Parameters and Functions table's Filters: a button that drops down what the table lists, by where entries are
 * defined (Global, Reactions and Rules, Applications, and which application), their type (parameters, functions) and
 * where they came from (user declared, auto-generated, preexisting). Like the welcome window's Filters, it says how many
 * choices narrow the table, so a narrowed table is never mistaken for a short one. Ticking a choice leaves the list open.
 */
@SuppressWarnings("serial")
public class ParametersFilterButton extends JButton {

	/** What the table lists. <code>application</code> null: every application. */
	public record Filter(boolean global, boolean reactions, boolean applications, SimulationContext application,
			boolean parameters, boolean functions, boolean userDeclared, boolean autoGenerated, boolean preexisting) {

		/** Everything but VCell's own symbols and functions, as the table first shows. */
		public static Filter defaults() {
			return new Filter(true, true, true, null, true, true, true, true, false);
		}

		/** How many choices differ from the defaults. */
		public int changes() {
			Filter defaults = Filter.defaults();
			int changes = 0;
			if (this.global != defaults.global) changes++;
			if (this.reactions != defaults.reactions) changes++;
			if (this.applications != defaults.applications) changes++;
			if (this.application != null) changes++;
			if (this.parameters != defaults.parameters) changes++;
			if (this.functions != defaults.functions) changes++;
			if (this.userDeclared != defaults.userDeclared) changes++;
			if (this.autoGenerated != defaults.autoGenerated) changes++;
			if (this.preexisting != defaults.preexisting) changes++;
			return changes;
		}
	}

	private final Consumer<Filter> onChange;
	private Filter filter = Filter.defaults();
	private List<SimulationContext> applications = new ArrayList<>();

	/** @param onChange told each time the filter changes */
	public ParametersFilterButton(Consumer<Filter> onChange) {
		this.onChange = onChange;
		this.setName("ParametersFilterButton");
		this.setToolTipText("What the table lists: where entries are defined, their type, and where they came from");
		this.addActionListener(e -> this.createMenu().show(this, 0, this.getHeight()));
		this.updateText();
	}

	public Filter getFilter() {
		return this.filter;
	}

	/** Sets the filter, as if chosen (the table follows). */
	public void setFilter(Filter filter) {
		this.filter = filter;
		this.updateText();
		this.onChange.accept(filter);
	}

	/** The model's applications, to choose among; a chosen one that's gone goes back to all of them. */
	public void setApplications(List<SimulationContext> applications) {
		this.applications = new ArrayList<>(applications);
		if (this.filter.application() != null && !this.applications.contains(this.filter.application())) {
			Filter f = this.filter;
			this.setFilter(new Filter(f.global(), f.reactions(), f.applications(), null, f.parameters(), f.functions(), f.userDeclared(), f.autoGenerated(), f.preexisting()));
		}
	}

	JPopupMenu createMenu() {
		JPopupMenu menu = new JPopupMenu();
		menu.setName("ParametersFilterMenu");
		Filter f = this.filter;

		menu.add(ParametersFilterButton.heading("Defined In"));
		menu.add(this.check("Global", f.global(), (c, on) -> new Filter(on, c.reactions(), c.applications(), c.application(), c.parameters(), c.functions(), c.userDeclared(), c.autoGenerated(), c.preexisting())));
		menu.add(this.check("Reactions and Rules", f.reactions(), (c, on) -> new Filter(c.global(), on, c.applications(), c.application(), c.parameters(), c.functions(), c.userDeclared(), c.autoGenerated(), c.preexisting())));
		menu.add(this.check("Applications", f.applications(), (c, on) -> new Filter(c.global(), c.reactions(), on, c.application(), c.parameters(), c.functions(), c.userDeclared(), c.autoGenerated(), c.preexisting())));
		if (this.applications.size() > 1) { // which of them, when there's a choice
			ButtonGroup group = new ButtonGroup();
			List<SimulationContext> choices = new ArrayList<>();
			choices.add(null);
			choices.addAll(this.applications);
			for (SimulationContext application : choices) {
				String label = "    " + (application == null ? "All Applications" : application.getName());
				JRadioButtonMenuItem item = new JRadioButtonMenuItem(label, application == f.application());
				item.setName("ParametersFilter_" + (application == null ? "AllApplications" : "Application_" + application.getName()));
				item.setEnabled(f.applications());
				item.addActionListener(e -> {
					Filter c = this.filter;
					this.setFilter(new Filter(c.global(), c.reactions(), c.applications(), application, c.parameters(), c.functions(), c.userDeclared(), c.autoGenerated(), c.preexisting()));
				});
				group.add(item);
				menu.add(item);
			}
		}

		menu.addSeparator();
		menu.add(ParametersFilterButton.heading("Type"));
		menu.add(this.check("Parameters", f.parameters(), (c, on) -> new Filter(c.global(), c.reactions(), c.applications(), c.application(), on, c.functions(), c.userDeclared(), c.autoGenerated(), c.preexisting())));
		menu.add(this.check("Functions", f.functions(), (c, on) -> new Filter(c.global(), c.reactions(), c.applications(), c.application(), c.parameters(), on, c.userDeclared(), c.autoGenerated(), c.preexisting())));

		menu.addSeparator();
		menu.add(ParametersFilterButton.heading("Origin"));
		JCheckBoxMenuItem userDeclared = this.check(ParameterOrigin.USER_DECLARED.getLabel(), f.userDeclared(), (c, on) -> new Filter(c.global(), c.reactions(), c.applications(), c.application(), c.parameters(), c.functions(), on, c.autoGenerated(), c.preexisting()));
		userDeclared.setToolTipText(ParameterOrigin.USER_DECLARED.getDescription());
		menu.add(userDeclared);
		JCheckBoxMenuItem autoGenerated = this.check(ParameterOrigin.AUTO_GENERATED.getLabel(), f.autoGenerated(), (c, on) -> new Filter(c.global(), c.reactions(), c.applications(), c.application(), c.parameters(), c.functions(), c.userDeclared(), on, c.preexisting()));
		autoGenerated.setToolTipText(ParameterOrigin.AUTO_GENERATED.getDescription());
		menu.add(autoGenerated);
		JCheckBoxMenuItem preexisting = this.check(ParameterOrigin.PREEXISTING.getLabel(), f.preexisting(), (c, on) -> new Filter(c.global(), c.reactions(), c.applications(), c.application(), c.parameters(), c.functions(), c.userDeclared(), c.autoGenerated(), on));
		preexisting.setToolTipText(ParameterOrigin.PREEXISTING.getDescription());
		menu.add(preexisting);

		menu.addSeparator();
		JMenuItem reset = new JMenuItem("Reset Filters");
		reset.setName("ParametersFilterReset");
		reset.setEnabled(f.changes() > 0);
		reset.addActionListener(e -> this.setFilter(Filter.defaults()));
		menu.add(reset);
		return menu;
	}

	// a choice that leaves the list open, so several can be ticked in turn; it changes the filter as it is when clicked
	private JCheckBoxMenuItem check(String label, boolean on, java.util.function.BiFunction<Filter, Boolean, Filter> change) {
		JCheckBoxMenuItem item = new JCheckBoxMenuItem(label, on);
		item.setName("ParametersFilter_" + label.replaceAll("[^A-Za-z]", ""));
		item.putClientProperty("CheckBoxMenuItem.doNotCloseOnMouseClick", Boolean.TRUE);
		item.addActionListener(e -> this.setFilter(change.apply(this.filter, item.isSelected())));
		return item;
	}

	private static JMenuItem heading(String text) {
		JMenuItem heading = new JMenuItem(text);
		heading.setEnabled(false);
		heading.setFont(heading.getFont().deriveFont(java.awt.Font.BOLD));
		return heading;
	}

	private void updateText() {
		int changes = this.filter.changes();
		this.setText("Filters" + (changes > 0 ? " (" + changes + ")" : "") + " ▾");
	}
}
