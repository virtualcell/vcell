package cbit.vcell.client.desktop.biomodel;

import java.beans.PropertyChangeListener;
import java.util.ArrayList;
import java.util.List;

import cbit.vcell.mapping.ParameterContext.LocalParameter;
import cbit.vcell.mapping.SimulationContext.SimulationContextParameter;
import cbit.vcell.model.EditableSymbolTableEntry;
import cbit.vcell.model.Kinetics;
import cbit.vcell.model.Kinetics.KineticsParameter;
import cbit.vcell.model.Model;
import cbit.vcell.model.RbmKineticLaw;
import cbit.vcell.parser.ASTFuncNode;
import cbit.vcell.parser.Expression;
import cbit.vcell.parser.ExpressionException;
import cbit.vcell.parser.NameScope;
import cbit.vcell.parser.SymbolTableEntry;
import cbit.vcell.parser.SymbolTableFunctionEntry;
import cbit.vcell.units.VCUnitDefinition;

/**
 * Where a parameter or function in the Parameters and Functions table came from: declared by the user, generated by
 * VCell as part of something else (a species, a structure, a kinetic law, an application's mapping), or there before
 * the model (VCell's own constants and functions).
 */
public enum ParameterOrigin {
	USER_DECLARED("User declared", "Parameters and functions you created: global and application parameters, and those you added to a kinetic law"),
	AUTO_GENERATED("Auto-generated", "Made with something else: a species, a structure's size, a kinetic law's parameters, an application's initial conditions"),
	PREEXISTING("Preexisting", "VCell's own constants and functions, there before any model: t, x, KMOLE, sin, exp...");

	private final String label;
	private final String description;

	ParameterOrigin(String label, String description) {
		this.label = label;
		this.description = description;
	}

	public String getLabel() {
		return this.label;
	}

	public String getDescription() {
		return this.description;
	}

	/** Where this entry came from. */
	public static ParameterOrigin of(EditableSymbolTableEntry entry) {
		if (entry instanceof Model.ReservedSymbol || entry instanceof PredefinedEntry) return ParameterOrigin.PREEXISTING;
		if (entry instanceof Model.ModelParameter || entry instanceof SimulationContextParameter) return ParameterOrigin.USER_DECLARED; // these have no other role
		if (entry instanceof KineticsParameter parameter && parameter.getRole() == Kinetics.ROLE_UserDefined) return ParameterOrigin.USER_DECLARED;
		if (entry instanceof LocalParameter parameter && parameter.getRole() == RbmKineticLaw.RbmKineticLawParameterType.UserDefined) return ParameterOrigin.USER_DECLARED;
		return ParameterOrigin.AUTO_GENERATED;
	}

	/**
	 * VCell's own symbols and functions, as the Predefined Expressions tab listed them: the model's reserved symbols
	 * (t, x, _F_, KMOLE...), its model functions, and the math functions expressions may use (sin, exp...).
	 */
	public static List<EditableSymbolTableEntry> preexisting(Model model) {
		List<EditableSymbolTableEntry> entries = new ArrayList<>();
		if (model != null) {
			for (Model.ReservedSymbol symbol : model.getReservedSymbols()) entries.add(symbol);
			for (Model.ModelFunction function : model.getModelFunctions()) {
				entries.add(new PredefinedEntry(function, function.getFunctionDeclaration(), function.getDescription()));
			}
		}
		for (ASTFuncNode.PredefinedSymbolTableFunctionEntry function : ASTFuncNode.predefinedSymbolTableFunctionEntries) {
			entries.add(new PredefinedEntry(function, function.getFunctionDeclaration(), function.getDescription()));
		}
		return entries;
	}

	/** A predefined function, read-only in the table: its declaration (e.g. "sin(x)") as its name. */
	public static final class PredefinedEntry implements EditableSymbolTableEntry {
		private final SymbolTableFunctionEntry function;
		private final String name;
		private final String description;

		PredefinedEntry(SymbolTableFunctionEntry function, String name, String description) {
			this.function = function;
			this.name = name;
			this.description = description == null ? "" : description;
		}

		public SymbolTableFunctionEntry getFunction() {
			return this.function;
		}

		@Override public String getName() { return this.name; }
		@Override public String getDescription() { return this.description; }
		@Override public Expression getExpression() { return this.function.getExpression(); }
		@Override public NameScope getNameScope() { return this.function.getNameScope(); }
		@Override public VCUnitDefinition getUnitDefinition() { return this.function.getUnitDefinition(); }
		@Override public int getIndex() { return this.function.getIndex(); }
		@Override public double getConstantValue() throws ExpressionException { return this.function.getConstantValue(); }
		@Override public boolean isConstant() throws ExpressionException { return this.function.isConstant(); }
		@Override public int compareTo(SymbolTableEntry other) { return this.name.compareTo(other.getName()); }

		// VCell's own: nothing about it is edited here
		@Override public boolean isExpressionEditable() { return false; }
		@Override public boolean isUnitEditable() { return false; }
		@Override public boolean isNameEditable() { return false; }
		@Override public boolean isDescriptionEditable() { return false; }
		@Override public void setName(String name) { throw new UnsupportedOperationException("predefined"); }
		@Override public void setExpression(Expression expression) { throw new UnsupportedOperationException("predefined"); }
		@Override public void setUnitDefinition(VCUnitDefinition unit) { throw new UnsupportedOperationException("predefined"); }
		@Override public void setDescription(String description) { throw new UnsupportedOperationException("predefined"); }
		@Override public void addPropertyChangeListener(PropertyChangeListener listener) {}
		@Override public void removePropertyChangeListener(PropertyChangeListener listener) {}
	}
}
